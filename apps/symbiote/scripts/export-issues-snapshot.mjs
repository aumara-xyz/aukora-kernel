#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const REPO = process.env.GH_REPO || "aumara-xyz/aukora-symbiote";
const MAX_ISSUES = process.env.ISSUES_SNAPSHOT_LIMIT || "500";
const MAX_BUFFER = 100 * 1024 * 1024;

const root = execFileSync("git", ["rev-parse", "--show-toplevel"], {
  encoding: "utf8",
}).trim();
const head = execFileSync("git", ["rev-parse", "HEAD"], {
  encoding: "utf8",
}).trim();
const generatedAt = new Date().toISOString();

const indexPath = path.join(root, "docs", "ISSUES_SNAPSHOT.md");
const outDir = path.join(root, "docs", "issues-snapshot");

const redactionStats = new Map();
let redactionTotal = 0;

const redactionPatterns = [
  {
    reason: "private-key-pem",
    re: /-----BEGIN[A-Z ]*PRIVATE KEY-----[\s\S]*?-----END[A-Z ]*PRIVATE KEY-----/g,
  },
  {
    reason: "openrouter-key",
    re: /\bsk-or-v1-[A-Za-z0-9_-]{20,}\b/g,
  },
  {
    reason: "anthropic-key",
    re: /\bsk-ant-[A-Za-z0-9_-]{20,}\b/g,
  },
  {
    reason: "generic-sk-key",
    re: /\bsk-[A-Za-z0-9_-]{20,}\b/g,
  },
  {
    reason: "github-token",
    re: /\bgh[pousr]_[A-Za-z0-9_]{20,}\b/g,
  },
  {
    reason: "aws-access-key",
    re: /\bAKIA[A-Z0-9]{16}\b/g,
  },
  {
    reason: "bearer-token",
    re: /\bBearer\s+[A-Za-z0-9._~+/=-]{20,}\b/gi,
  },
  {
    reason: "local-user-path",
    re: /\/[Uu]sers\/[^"'\s`<>),]+(?:\/[^"'\s`<>),]+)*/g,
  },
  {
    reason: "local-home-path",
    re: /\/home\/[^"'\s`<>),]+(?:\/[^"'\s`<>),]+)*/g,
  },
  {
    reason: "inline-secret-assignment",
    re: /\b(api[_-]?key|secret|token|password)\s*[:=]\s*["']?[^"'\s`]{16,}/gi,
  },
];

function gh(args) {
  return execFileSync("gh", args, {
    cwd: root,
    encoding: "utf8",
    maxBuffer: MAX_BUFFER,
  });
}

function redact(input) {
  if (!input) return "";
  let output = String(input);
  for (const { reason, re } of redactionPatterns) {
    output = output.replace(re, () => {
      redactionTotal += 1;
      redactionStats.set(reason, (redactionStats.get(reason) || 0) + 1);
      return `[REDACTED:${reason}]`;
    });
  }
  return output;
}

function mdCell(value) {
  return String(value ?? "")
    .replace(/\|/g, "\\|")
    .replace(/\r?\n/g, " ")
    .trim();
}

function labelNames(issue) {
  return (issue.labels || []).map((label) => label.name).sort();
}

function issueFileName(issueNumber) {
  return `issue-${String(issueNumber).padStart(3, "0")}.md`;
}

function authorName(author) {
  if (!author) return "unknown";
  if (typeof author === "string") return author;
  return author.login || author.name || "unknown";
}

function writeIssueFile(issue, view) {
  const labels = labelNames(issue);
  const comments = view.comments || [];
  const lines = [
    `# #${issue.number} ${redact(issue.title)}`,
    "",
    "Generated by `scripts/export-issues-snapshot.sh`; do not edit by hand.",
    "",
    `- State: ${issue.state}`,
    `- Labels: ${labels.length ? labels.join(", ") : "none"}`,
    `- Created: ${issue.createdAt || "unknown"}`,
    `- Updated: ${issue.updatedAt || "unknown"}`,
    `- Closed: ${issue.closedAt || "not closed"}`,
    `- URL: ${issue.url || ""}`,
    "",
    "## Body",
    "",
    redact(view.body || "_No body._"),
    "",
    "## Comments",
    "",
  ];

  if (comments.length === 0) {
    lines.push("_No comments._", "");
  } else {
    comments.forEach((comment, index) => {
      lines.push(
        `### Comment ${index + 1} - ${authorName(comment.author)} - ${comment.createdAt || "unknown"}`,
        "",
        redact(comment.body || "_No body._"),
        "",
      );
    });
  }

  const fileName = issueFileName(issue.number);
  fs.writeFileSync(path.join(outDir, fileName), `${lines.join("\n").trim()}\n`, "utf8");
  return fileName;
}

const issues = JSON.parse(
  gh([
    "issue",
    "list",
    "--repo",
    REPO,
    "--state",
    "all",
    "--limit",
    MAX_ISSUES,
    "--json",
    "number,title,state,labels,createdAt,updatedAt,closedAt,url",
  ]),
).sort((a, b) => b.number - a.number);

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

const issueRows = [];
for (const issue of issues) {
  const view = JSON.parse(
    gh([
      "issue",
      "view",
      String(issue.number),
      "--repo",
      REPO,
      "--json",
      "body,comments",
    ]),
  );
  const fileName = writeIssueFile(issue, view);
  issueRows.push({ issue, fileName });
}

const redactionSummary =
  redactionTotal === 0
    ? "0"
    : `${redactionTotal} (${[...redactionStats.entries()]
        .map(([reason, count]) => `${reason}: ${count}`)
        .join(", ")})`;

const openCount = issues.filter((issue) => issue.state === "OPEN").length;
const closedCount = issues.filter((issue) => issue.state === "CLOSED").length;
const indexLines = [
  "# GitHub Issues Snapshot",
  "",
  "Generated by `scripts/export-issues-snapshot.sh`; do not edit by hand.",
  "",
  `- Snapshot timestamp: ${generatedAt}`,
  `- Repository: ${REPO}`,
  `- HEAD SHA at generation: ${head}`,
  `- Issue count: ${issues.length} (${openCount} open, ${closedCount} closed)`,
  `- Redactions: ${redactionSummary}`,
  "- Photograph, not feed \u2014 true as of the commit that carries it. Regenerate before each planning session.",
  "",
  "Per-issue bodies and comments are split into `docs/issues-snapshot/` so repo-confined read tools can inspect focused files without loading the whole tracker.",
  "",
  "## Summary",
  "",
  "| # | State | Labels | Title | Snapshot file |",
  "|---:|---|---|---|---|",
];

for (const { issue, fileName } of issueRows) {
  const labels = labelNames(issue).join(", ") || "none";
  indexLines.push(
    `| ${issue.number} | ${issue.state} | ${mdCell(labels)} | ${mdCell(redact(issue.title))} | [${fileName}](issues-snapshot/${fileName}) |`,
  );
}

fs.writeFileSync(indexPath, `${indexLines.join("\n")}\n`, "utf8");

console.log(`wrote ${path.relative(root, indexPath)}`);
console.log(`wrote ${issueRows.length} issue files under ${path.relative(root, outDir)}`);
console.log(`redactions: ${redactionSummary}`);
